let current = 'en';
export function detectLang() {
  try { const saved = JSON.parse(localStorage.getItem('cvstudio:uiLang')); if (STRINGS[saved]) return saved; } catch {}
  const nav = (navigator.languages || [navigator.language || 'en']).map((l) => l.toLowerCase());
  for (const l of nav) { const base = l.slice(0, 2); if (STRINGS[base]) return base; }
  return 'en';
}
export function setLang(code) {
  current = STRINGS[code] ? code : 'en';
  try { localStorage.setItem('cvstudio:uiLang', JSON.stringify(current)); } catch {}
  const meta = UI_LANGS.find((l) => l.code === current);
  document.documentElement.lang = meta.html;
  return current;
}
export const getLang = () => current;
/** t('cat.count', { n: 6 }) — falls back to English, then to the key. */
export function t(key, vars) {
  let s = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
  return s;
}

